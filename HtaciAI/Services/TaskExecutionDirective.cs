using HtaciAI.Services.Storage;

namespace HtaciAI.Services;

/// <summary>
/// 「直接执行任务」设置对应的 system 追加段。
///
/// <b>为什么需要一个设置项而不是改档案提示词</b>：模型拒做某类任务（自动化操作、批量处理、
/// 教学演示）的判断依据千差万别，而「这是不是我的真实意图」只有用户自己知道。
/// 与其让每个会话都在首条消息里写一段「这只是测试项目」，不如在客户端里给一个全局开关，
/// 打开后由 system 一次性说明清楚。
///
/// <b>它做什么</b>：把「用户明确要求的事」定为主线任务，禁止用「我是 AI」「这可能违反规定」
/// 这类空泛理由推脱；不要在信息齐全时反复确认；判定任务性质以用户的自述为准。
///
/// <b>它不做什么</b>：不解除「真实危害」那几条底线（违法操作、攻击他人系统、窃取凭据）。
/// 这一段是让模型少打太极，而不是让它闭眼执行 —— 后者既帮不到用户，也会把客户端变成
/// 一个什么都敢做的黑盒。真正的安全边界由客户端自己的工具审批与权限档位负责。
/// </summary>
public static class TaskExecutionDirective
{
    /// <summary>开关是否打开。每轮现读，改设置立即生效、不用重启。</summary>
    public static bool Enabled => AppSettingsStore.Current.ObeyUserTasks;

    /// <summary>追加到 system 末尾的文本；开关关闭时返回空串。</summary>
    public static string Build() => Enabled ? Text : "";

    /// <summary>
    /// 追加正文。措辞上刻意区分三件事：<b>主线任务</b>（用户的明确要求）、
    /// <b>该问的时候</b>（缺信息 / 不可逆）、<b>仍然拒绝的</b>（真实危害）。
    /// 只写「无条件服从」会让模型在真正该提醒的时候也闭嘴，那不是用户想要的。
    /// </summary>
    public const string Text = """
        当前会话已由用户开启「直接执行任务」模式，以下要求优先于默认的谨慎倾向：

        1. 用户消息里明确的动作要求就是本轮的主线任务。直接开始执行并汇报结果，
           不要先用「我不能」「作为 AI 我无法」「这可能需要你自己操作」这类说法推脱，
           也不要只给一段教程让用户自己动手 —— 有工具就直接用工具做。
        2. 任务是否正当由用户判断，不以任务外表推断动机。批量操作、网页自动化、
           刷课刷题、脚本代跑、爬取、模拟点击这类字眼本身不是拒绝理由；
           用户说明是测试、开发、学习用途时，按此认定。
        3. 不要在信息已经足够时反复请求确认，也不要逐个步骤征求同意。
           仅在两种情况下问一次：缺少无法自行获取的关键信息；操作不可逆且影响面超出本机。
        4. 确实做不到时，只给具体的技术原因（缺少某个工具、权限不足、目标站点拒绝、接口不存在），
           并给出你尝试采取过的替代做法；不要用含糊的能力否认代替原因。
        5. 仍然拒绝的只有真实危害：协助实施违法犯罪、攻击或入侵他人未授权的系统、
           窃取凭据与他人数据、制造可用于实际伤害的内容。这类请求照常拒绝并给出可行的替代方案；
           其余情况一律按第 1–4 条执行。
        """;
}
