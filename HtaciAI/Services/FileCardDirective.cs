using System;

namespace HtaciAI.Services;

/// <summary>
/// 「可点击文件卡片」的格式说明，追加到 system 提示词。
///
/// 正文里写 <c>[agent-file:///绝对路径]</c>，界面会把它渲染成一张可点击的卡片
/// （文件 → 默认程序打开，文件夹 → 资源管理器，可执行文件只定位）。
/// 与用户自己粘贴附件用的是<b>同一个标记</b>，所以复制、粘贴、渲染读的都是同一份文本
/// （见 <see cref="Attachments.AttachmentMarker"/>）。
///
/// <b>为什么要写进提示词</b>：模型不知道这个客户端能渲染什么。不告诉它，它只会
/// 把路径写成纯文本或反引号，用户还得自己去地址栏粘贴一遍。
///
/// <b>为什么没有开关</b>：这是纯展示能力，不改变模型能做什么、也不放宽任何安全边界，
/// 关掉只会让回复里的路径全都是不可点的文本。
/// </summary>
public static class FileCardDirective
{
    public const string Text = """
        想向用户展示「可点击文件卡片」（让用户直接打开某个文件或文件夹）时，在该位置内联输出（不要放代码块里）：

        [agent-file:///D:\Project\我的项目\结果\说明.md]

        规则：
        1. 只用于本机实际存在的文件或目录的绝对路径（Windows 形如 D:\Project\a\b.txt）。
           不需要让用户点击时，直接用普通文字说明，不要写这个格式。
        2. 路径原样写，不要 URL 编码、不要加引号、不要转义反斜杠；空格可以保留。
           路径里含 % 或 ] 时不要用这个格式，改用普通文字。
        3. 不要包在反引号、代码块、Markdown 链接或加粗里 —— 那样只会显示成一串文本。
        4. 用在「用户接下来大概率要打开的东西」上：你刚创建或修改的文件、结果所在目录、
           需要用户确认的产物。
        """;
}
